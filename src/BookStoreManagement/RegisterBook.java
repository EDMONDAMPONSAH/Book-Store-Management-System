    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String name = jTextField1.getText();
        String author = jTextField2.getText();
        String price = jTextField3.getText();
        DateTimeFormatter df = DateTimeFormatter.ofPattern("dd-MM-yyyy");
        LocalDateTime now = LocalDateTime.now();
        String dadded = df.format(now);
        DateTimeFormatter dt = DateTimeFormatter.ofPattern("HH:mm:ss");
        LocalDateTime nw = LocalDateTime.now();
        String tadded = dt.format(nw);

        if (name.equals("Enter Book Name")) {
            JOptionPane.showMessageDialog(null, "<html><b style=\"font-size:12px;color:red;\">Enter Name of Book</b></html>", "Message", JOptionPane.ERROR_MESSAGE);
        } else if (author.equals("Enter Author Name")) {
            JOptionPane.showMessageDialog(null, "<html><b style=\"font-size:12px;color:red;\">Enter Name of Author</b></html>", "Message", JOptionPane.ERROR_MESSAGE);
        } else if (price.equals("Enter Book Price")) {
            JOptionPane.showMessageDialog(null, "<html><b style=\"font-size:12px;color:red;\">Enter Price of Book</b></html>", "Message", JOptionPane.ERROR_MESSAGE);
        } else {
            con = database.connectDB();
            try {
                pst = con.prepareStatement("insert into abooks(idd,bname,aname,price,dadded)values(?,?,?,?,?)");
                pst.setString(1, jLabel4.getText());
                pst.setString(2, name);
                pst.setString(3, author);
                pst.setString(4, price);
                pst.setString(5, dadded + "  " + tadded);
                pst.executeUpdate();
                JOptionPane.showMessageDialog(null, "<html><b style=\"font-size:12px;\">SUCCESSFULLY REGISTERED</b></html>", "Message", JOptionPane.INFORMATION_MESSAGE);
                autoID();
                resetField();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            } finally {
                try {
                    pst.close();
                    rs.close();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(null, e);
                }
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

