    private void autoID() {
        try {
            con = database.connectDB();
            st = con.createStatement();
            rs = st.executeQuery("select max(idd) from abooks");
            rs.next();
            rs.getString("max(idd)");
            if (rs.getString("max(idd)") == null) {
                jLabel4.setText("Bk0001");
            } else {
                long idd = Long.parseLong(rs.getString("max(idd)").substring(2, rs.getString("max(idd)").length()));
                idd++;
                jLabel4.setText("Bk" + String.format("%04d", idd));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        } finally {
            try {
                st.close();
                rs.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }

    }

