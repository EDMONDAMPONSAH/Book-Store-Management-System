    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        try {
            int a = JOptionPane.showConfirmDialog(null, "Do you really want to remove selected book from My Books?", "Confirm", JOptionPane.YES_NO_OPTION);
            if (a == 0) {
                DefaultTableModel dft = (DefaultTableModel) jTable1.getModel();
                int selectedIndex = jTable1.getSelectedRow();
                String idd = dft.getValueAt(selectedIndex, 0).toString();
                con = database.connectDB();
                pst = con.prepareStatement("delete from mbooks where idd ='" + idd + "'");
                pst.executeUpdate();
                loadTable("");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        } finally {
            try {
                pst.close();
                rs.close();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }
    }//GEN-LAST:event_jTable1MouseClicked


