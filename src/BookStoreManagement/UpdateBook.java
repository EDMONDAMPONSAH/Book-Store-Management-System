    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String name = jTextField4.getText();
        String author = jTextField5.getText();
        String price = jTextField6.getText();
        if (name.equals("Enter Book Name")) {
            JOptionPane.showMessageDialog(this, "<html><b style=\"font-size:12px;color:red;\">Enter Name of Book</b></html>", "Message", JOptionPane.ERROR_MESSAGE);
        } else if (author.equals("Enter Author Name")) {
            JOptionPane.showMessageDialog(this, "<html><b style=\"font-size:12px;color:red;\">Enter Name of Author</b></html>", "Message", JOptionPane.ERROR_MESSAGE);
        } else if (price.equals("Enter Book Price")) {
            JOptionPane.showMessageDialog(this, "<html><b style=\"font-size:12px;color:red;\">Enter Price of Book</b></html>", "Message", JOptionPane.ERROR_MESSAGE);
        } else {
            try {
                int a = JOptionPane.showConfirmDialog(this, "Do you really want to make changes to Book?", "Confirm", JOptionPane.YES_NO_OPTION);
                if (a == 0) {
                    con = database.connectDB();
                    pst = con.prepareStatement("update abooks set bname=?,aname=?,price=? where idd=?");
                    pst.setString(1, name);
                    pst.setString(2, author);
                    pst.setString(3, price);
                    pst.setString(4, jLabel8.getText());
                    pst.executeUpdate();
                    dispose();
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, e);
            } finally {
                try {
                    pst.close();
                    rs.close();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, e);
                }
            }

        }
    }//GEN-LAST:event_jButton3ActionPerformed

