    private void loadID() {
        try {
            con = database.connectDB();
            pst = con.prepareStatement("select * from abooks where idd='" + idd + "'");
            rs = pst.executeQuery();
            if (rs.next()) {
                jLabel8.setText(idd);
                jTextField4.setText(rs.getString("bname"));
                jTextField4.setForeground(Color.black);
                jTextField5.setText(rs.getString("aname"));
                jTextField5.setForeground(Color.black);
                jTextField6.setText(rs.getString("price"));
                jTextField6.setForeground(Color.black);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        } finally {
            try {
                pst.close();
                rs.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, e);
            }
        }
    }

